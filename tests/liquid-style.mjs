import assert from 'node:assert/strict';
import * as W from '../dist/world.mjs';
import * as C from '../dist/construction.mjs';
import {LIQUID_PRESETS,normalizeLiquidStyle,liquidPresetName,applyLiquidStyle,liquidVertexStyle} from '../dist/liquid-style.mjs';
import {deriveLiquids,liquidMeshData,createLiquidCache} from '../dist/liquid-flow.mjs';
import {liquidColorShader,liquidEmissionShader} from '../dist/liquid-shader.mjs';
import {mountLiquidControls} from '../dist/liquid-controls.mjs';
import {parseHTML} from 'linkedom';
assert.equal(LIQUID_PRESETS.length,8);
const blue=normalizeLiquidStyle('lava',LIQUID_PRESETS.find(p=>p.id==='bluefire'));
const green=normalizeLiquidStyle('water',LIQUID_PRESETS.find(p=>p.id==='toxic'));
assert.equal(blue.opacity,1);assert.equal(liquidPresetName('water',green),'Eau toxique');
assert.equal(normalizeLiquidStyle('water',{colorA:'bad',speed:-99,opacity:9}).speed,0);
const map=W.newMap('style','Style',48,48);W.prepareBlocks(map);
const world={maps:[map],active:map.id};
const item={kind:'block',material:'lava',w:1,d:1,h:1,step:1,liquidStyle:blue};
const [source]=C.placement(item,{x:12.5,y:12.5,z:0},world,()=> 'source');
assert.deepEqual(source.liquidStyle,blue);assert.equal(source.light.color,blue.colorA);
const water=C.blockObject('water',32,32,0,1,1,1,0,'water');applyLiquidStyle(water,green);
map.objects=[source,water];
const serialized=JSON.stringify(map),result=deriveLiquids(map,W);
assert.equal(JSON.stringify(map),serialized);
assert(result.cells.some(b=>!b.source&&b.kind==='lava'));
assert(result.cells.some(b=>!b.source&&b.kind==='water'));
assert(result.cells.every(b=>JSON.stringify(b.style)===JSON.stringify(b.kind==='lava'?blue:green)));
const batches=liquidMeshData(result);
for(const b of batches){
 assert.equal(b.positions.length,b.colorA.length);assert.equal(b.positions.length,b.colorB.length);assert.equal(b.positions.length,b.styleParams.length);
 const data=liquidVertexStyle(b.kind,b.kind==='lava'?blue:green);
 assert.deepEqual(b.colorA.slice(0,3),data.a);assert.deepEqual(b.colorB.slice(0,3),data.b);assert.deepEqual(b.styleParams.slice(0,3),data.params);
}
const cache=createLiquidCache(),first=cache(map,W,'mj');applyLiquidStyle(source,{colorA:'#ff0000'});map.buildRevision=(map.buildRevision||0)+1;
assert.notEqual(cache(map,W,'mj'),first);assert(cache(map,W,'mj').cells.filter(b=>b.kind==='lava').every(b=>b.style.colorA==='#ff0000'));
const legacy=W.newMap('old','Old',24,24);W.prepareBlocks(legacy);W.setBlock(legacy,10,10,0,'water');assert(deriveLiquids(legacy,W).cells.every(b=>b.style.colorA===normalizeLiquidStyle('water').colorA));
assert(liquidColorShader(false).includes('crack'));assert(liquidColorShader(true).includes('diffuseColor.a*=vLiquidParams.x'));assert(liquidEmissionShader(false).includes('vLiquidParams.z'));
const {document}=parseHTML('<html><body><div id="root"></div></body></html>'),root=document.getElementById('root');
let changed=null;mountLiquidControls(root,'water',green,s=>changed=s);assert.equal(root.querySelectorAll('input[type="color"]').length,2);assert.equal(root.querySelectorAll('input[type="range"]').length,3);
root.querySelector('button').onclick();assert.deepEqual(changed,normalizeLiquidStyle('water'));
mountLiquidControls(root,'lava',blue,()=>{throw Error('locked source')},{disabled:true});assert.equal(root.querySelectorAll('input[type="range"]').length,2);assert([...root.querySelectorAll('input,select,button')].every(el=>el.disabled));
console.log('PASS: presets, normalized saved source styles, inherited flow, vertex attributes, recoloring, legacy maps and editor controls.');
