import assert from 'node:assert/strict';
import * as W from '../dist/world.mjs';
import {boxesNear,cameraBoxEntry} from '../dist/navigation.mjs';
import {blockLightSources} from '../dist/block-tools.mjs';
import {lightCandidates} from '../dist/light-index.mjs';
import {createPartyVisionCache} from '../dist/party-vision.mjs';
const map=W.newMap('audit','Audit',48,48);W.prepareBlocks(map);
const actor=W.newObject('hero',20,20,'actor');map.objects=[actor];
const p={x:20.5,y:2,z:20.5};
W.setBlock(map,20,20,0,'stone',.5);
let before=boxesNear(map,p,5,actor.id),after=boxesNear(map,p,5,actor.id);
assert.equal(before[0],after[0],'stationary voxel windows reuse geometry');
const half=before.find(b=>b.x===20.5&&b.z===20.5&&b.y===0);assert.equal(half.h,.5);
W.setBlock(map,20,20,0,'stone',1);
after=boxesNear(map,p,5,actor.id);assert.notEqual(before[0],after[0]);assert.equal(after.find(b=>b.x===20.5&&b.z===20.5&&b.y===0).h,1);
W.digGround(map,19,20);assert.equal(boxesNear(map,p,5,actor.id).find(b=>b.x===19.5&&b.z===20.5&&b.y===-200).h,199);
const other=W.newObject('hero',21,20,'other');map.objects.push(other);
const movingBoxes=()=>boxesNear(map,p,5,actor.id,null,true);
assert(movingBoxes().some(b=>b.x===21.5&&b.z===20.5&&b.h===1.8));
other.x=22;assert(movingBoxes().some(b=>b.x===22.5&&b.z===20.5&&b.h===1.8));
assert.equal(cameraBoxEntry({x:0,y:.5,z:0},{x:4,y:.5,z:0},{x:2,y:0,z:0,w:1,h:1,d:1},.1),.35);
assert.equal(cameraBoxEntry({x:0,y:.5,z:0},{x:4,y:.5,z:0},{x:2,y:0,z:10,w:2,h:1,d:4,angle:1},.1),Infinity);
const sources=Array.from({length:128},(_,i)=>({x:(i%16)*12,y:Math.floor(i/16)*12,radius:5+i%7,power:.8,color:'#ffd294'}));
let total=0;
for(let y=-8;y<100;y+=3)for(let x=-8;x<200;x+=3){
 const candidates=lightCandidates(sources,x,y),hits=a=>a.filter(s=>Math.hypot(s.x-x,s.y-y)<s.radius);
 assert.deepEqual(hits(candidates),hits(sources));total+=candidates.length;
}
assert(total<128*72*36/4,'local index substantially cuts candidate visits');
const glow=Object.keys(W.BLOCKS).find(k=>W.BLOCKS[k].emissive);
W.setBlock(map,15,15,0,glow);const lights=blockLightSources(map);
assert(lights.length>0);assert.equal(blockLightSources(map)[0],lights[0]);
W.setBlock(map,15,15,0,null);assert.equal(blockLightSources(map).length,0);
actor.vision={range:12,far:16,angle:180,near:3.5};
const cache=createPartyVisionCache(()=>({allowed:true,detail:.8,haze:.1})),noLights={sources:[],walls:[]};
let result=cache.collect(map,[actor],noLights,0,{maxRays:5});const live=result.sight;
assert.equal(result.newlyExplored.get(actor.id).length,5);
result=cache.collect(map,[actor],noLights,0,{maxRays:5});
assert.equal(result.sight,live);assert.equal(live.size,10);assert.equal(result.newlyExplored.get(actor.id).length,5);
actor.x++;result=cache.collect(map,[actor],noLights,0,{maxRays:1});
assert.notEqual(result.sight,live);assert.equal(result.sight.size,1);
console.log('PASS: bounded camera terrain reuse, edit invalidation, live collision actors, exact light candidates, emitter reuse and incremental vision.');
