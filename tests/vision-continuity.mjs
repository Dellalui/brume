import assert from 'node:assert/strict';
import * as W from '../dist/world.mjs';
import {createPartyVisionCache} from '../dist/party-vision.mjs';
const map=W.newMap('continuity','Continuity',40,40);W.prepareBlocks(map);
const a=W.newObject('hero',20,24,'a');a.vision={range:12,far:16,angle:180,near:3.5};map.objects=[a];
const k='20,13';let blocked=false;
const perceive=(_m,_a,x,y)=>{const hidden=blocked&&W.cellKey(x,y)===k;return {allowed:!hidden,detail:hidden?0:.8,haze:0}};
const cache=createPartyVisionCache(perceive);
let lights={sources:[],walls:[]};
let r=cache.collect(map,[a],lights,0);
assert.equal(r.display.get(k),.8);assert(r.sight.has(k));
a.y--;r=cache.collect(map,[a],lights,0,{maxRays:1});
assert(r.pending);assert.equal(r.display.get(k),.8);assert(!r.sight.has(k));assert(!r.allowed.has(k));assert(!r.vision.has(k));
lights={sources:[{x:20,y:23,power:1}],walls:[]};
r=cache.collect(map,[a],lights,0,{maxRays:1});
assert.equal(r.display.get(k),.8);assert(!r.sight.has(k));
blocked=true;r=cache.collect(map,[a],lights,0);
assert(!r.display.has(k));assert(!r.allowed.has(k));
for(const [key,value] of r.display)assert.equal(value,Math.max(r.sight.get(key)?.detail||0,r.sight.get(key)?.haze||0));
blocked=false;a.y--;r=cache.collect(map,[a],lights,0);assert(r.display.has(k));
a.facing=Math.PI;r=cache.collect(map,[a],lights,0,{maxRays:1});assert(!r.display.has(k),'old view outside the new cone must disappear');
a.facing=0;r=cache.collect(map,[a],lights,0);assert(r.display.has(k));
r=cache.collect(map,[a],lights,1,{maxRays:1});assert(!r.display.has(k),'terrain/fog edit invalidates old presentation');
console.log('PASS: stable terrain through motion and light changes, fresh live visibility, occlusion, cone and topology invalidation.');
