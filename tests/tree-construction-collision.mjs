import assert from 'node:assert/strict';
import * as W from '../dist/world.mjs';
import {blockObject,placementError,overlap} from '../dist/construction.mjs';
import {treeConstructionBoxes} from '../dist/tree-construction-collision.mjs';
const map=W.newMap('test','Tree protection',64,64);W.prepareBlocks(map);
const tree={...W.newObject('tree',16,16,'tree'),w:8,d:8,height:5,baseZ:1,trunkRadius:.3,treeGraph:[[0,0,.5,.3,-1,'round'],[0,0,1.5,.26,0,'round'],[0,0,2.5,.22,1,'round'],[1,0,2.5,.15,2,'round'],[2,0,3.5,.05,3,'taper']]};
map.objects=[tree];
const block=(x,y,z,id='b')=>blockObject('stone',x,y,z,1,1,1,0,id);
assert(overlap(tree,block(20,20,1),map));assert(overlap(block(20,20,1),tree,map));
assert(placementError(map,[block(20,20,1)]).includes('arbre'));
assert(placementError(map,[block(21,20,3)]).includes('arbre'));
assert.equal(placementError(map,[block(23,23,1)]),'');
assert.equal(placementError(map,[block(20,20,0)]),'');
assert(W.blockPlacementError(map,20,20,1,'stone'));assert.equal(W.blockPlacementError(map,20,20,1,null),null);
assert.equal(W.blockPlacementError(map,23,23,1,'stone'),null);
const boxes=treeConstructionBoxes(tree,1);assert.strictEqual(boxes,treeConstructionBoxes(tree,1));assert(boxes.length>0);
tree.facing=Math.PI/2;assert.notStrictEqual(boxes,treeConstructionBoxes(tree,1));assert(W.blockPlacementError(map,20,21,3,'stone'));
tree.x+=10;assert.equal(W.blockPlacementError(map,20,20,1,'stone'),null);assert(W.blockPlacementError(map,30,20,1,'stone'));
tree.x-=10;tree.blocking=false;assert.equal(W.blockPlacementError(map,20,20,1,'stone'),null);
tree.blocking=true;map.objects=[block(20,20,1,'existing')];assert(placementError(map,[tree]).includes('arbre'));
console.log('PASS: cached tree hitboxes, rotations, movement, creative and voxel construction protection');
