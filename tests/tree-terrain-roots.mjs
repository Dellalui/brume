import assert from 'node:assert/strict';
import * as W from '../dist/world.mjs';
import * as T from '../dist/vendor/three.module.min.js';
import {treeExtent,validTreeGraph,unifiedTreeGeometry} from '../dist/unified-trees.mjs';
import {rootSurface,splitTreeRoots} from '../dist/tree-roots.mjs';
import {planTreePlanting,treePlantingPlan} from '../dist/tree-neighbors.mjs';
import {treeConstructionBoxes,boxIntersects} from '../dist/tree-construction-collision.mjs';
import {placementError} from '../dist/construction.mjs';
const map=W.newMap('roots','Stepped terrain',64,64);W.prepareBlocks(map);
W.setBlock(map,20,20,0,'grass');W.setBlock(map,19,20,0,'stone');W.setBlock(map,19,20,1,'stone',.5);
const graph=[[0,0,.5,.18,-1,'round'],[0,0,1.5,.15,0,'round'],[0,0,2.5,.07,1,'taper'],[1,0,.37,.09,0,'round'],[2,0,.37,.045,3,'taper'],[-1,0,.37,.09,0,'round'],[-2,0,.37,.045,5,'taper']];
const e=treeExtent(graph),o={...W.newObject('tree',0,0,'root-test'),...e,x:20.5-e.w/2,y:20.5-e.d/2,baseZ:1,treeGraph:graph,treeConfig:{rootFlare:.5,adaptCrowns:true}};
assert.equal(rootSurface(map,20.5,20.5,1),1);
assert.equal(rootSurface(map,21.5,20.5,1),0);
assert.equal(rootSurface(map,19.5,20.5,1),1.5);
const split=splitTreeRoots(graph);assert.equal(split.paths.length,2);assert.deepEqual(split.graph,graph.slice(0,3));
assert.equal(splitTreeRoots([[0,0,.3,.3,-1,'broken'],[1,0,.3,.3,0,'broken']]).paths.length,0);
const original=JSON.stringify(map),fitted=planTreePlanting(map,o),plan=treePlantingPlan(fitted);
assert.equal(plan.error,'');assert(plan.rootValidated);assert(validTreeGraph(fitted.treeGraph));assert.deepEqual(fitted.treeGraph.slice(0,3),graph.slice(0,3));
const roots=fitted.treeGraph.filter(n=>n[6]==='root');
assert(roots.some(n=>n[0]>.5&&n[2]<-.5),'root descends beside full block');
assert(roots.some(n=>n[0]<-.5&&n[2]>.45),'root climbs half block');
assert(roots.length<=24);assert(fitted.treeGraph.length<=120);
assert.equal(JSON.stringify(map),original,'preview never mutates terrain');
assert.deepEqual(planTreePlanting(map,o).treeGraph,fitted.treeGraph);
assert.equal(placementError(map,[fitted]),'','soil contact must not reject tree placement');
const geom=unifiedTreeGeometry(T,fitted.treeGraph);assert(geom.attributes.position.array.every(Number.isFinite));assert(geom.boundingBox.min.y<-.5);geom.dispose();
const boxes=treeConstructionBoxes(fitted,1);assert(boxes.some(b=>b.treeRoot&&b.baseZ<.5));
map.objects=[fitted];assert(W.blockPlacementError(map,21,20,0,'stone'),'lower root retains voxel placement protection');map.objects=[];
const wall={...W.newObject('block',21,20,'wall'),baseZ:0,w:1,d:1,height:3,material:'stone'};
map.objects=[wall];map.buildRevision=1;
const around=planTreePlanting(map,o);assert.equal(treePlantingPlan(around).error,'');assert(treeConstructionBoxes(around,1).filter(b=>b.treeRoot).every(b=>!boxIntersects(b,wall)));
assert.deepEqual(around.treeGraph.slice(0,3),graph.slice(0,3));
console.log('PASS: roots follow full and half voxel steps, keep crown stable, protect construction and avoid walls.');
