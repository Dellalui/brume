import assert from 'node:assert/strict';
import {IDBFactory} from 'fake-indexeddb';
import {capture,materialize} from '../dist/history.mjs';
import {partition,assemble,createWorldStorage} from '../dist/world-storage.mjs';
import * as W from '../dist/world.mjs';
const renamed={a:1,b:2};capture(renamed);delete renamed.a;renamed.c=3;assert.deepEqual(capture(renamed),{b:2,c:3});
const world=W.defaultWorld();const m=world.maps[0];W.prepareBlocks(m);
const before=structuredClone(world),s1=capture(world),untouched=s1.maps[0].objects[1];
m.objects[0].x+=1;const s2=capture(world);
assert.equal(s2.maps[0].objects[1],untouched);assert.notEqual(s2.maps[0].objects[0],s1.maps[0].objects[0]);assert.deepEqual(materialize(s1),before);
const restored=materialize(s2);restored.maps[0].objects[1].name='Other';assert.notEqual(untouched.name,'Other');assert.equal(capture(world),s2);
assert.deepEqual(assemble([...partition(world).values()]),world);
const legacy=structuredClone(world);delete legacy.maps[0].blocks;assert.deepEqual(assemble([...partition(legacy).values()]),legacy,'missing block field must not turn legacy terrain into empty voxels');
const db=new IDBFactory(),storage=createWorldStorage(db);assert.equal(await storage.load(),null);
const first=await storage.save(world);assert(first.changed>m.objects.length);
assert.deepEqual(await storage.load(),world);assert.equal((await storage.save(world)).changed,0);
m.objects[0].hp-=2;assert.equal((await storage.save(world)).changed,1,'one HP edit writes one record');
W.setBlock(m,3,3,0,'stone');await storage.save(world);assert.deepEqual(await storage.load(),world);
m.objects.pop();await storage.save(world);assert.deepEqual(await storage.load(),world);
const expected=structuredClone(world),queued=storage.save(world);world.maps[0].objects[0].name='After enqueue';await queued;assert.deepEqual(await storage.load(),expected,'queued saves retain their original snapshot');
await Promise.all([storage.save(world),storage.save({...world,active:world.maps.at(-1).id})]);assert.equal((await storage.load()).active,world.maps.at(-1).id);
const reopened=createWorldStorage(db);assert.deepEqual(await reopened.load(),await storage.load());
// A freshly opened writer must delete persisted records on its first save.
const reload=await reopened.load(),rm=reload.maps[0];
W.setBlock(rm,7,7,0,'stone');await reopened.save(reload);
const writer=createWorldStorage(db),loadedAgain=await writer.load(),lm=loadedAgain.maps[0];
W.setBlock(lm,7,7,0,null);lm.objects.pop();await writer.save(loadedAgain);
const checked=await createWorldStorage(db).load();assert.deepEqual(checked,loadedAgain,'deleted columns and objects stay deleted after reopening');
assert.equal(W.blockAt(checked.maps[0],7,7,0),null);
console.log('PASS: immutable shared history, legacy/voxel roundtrips, real IndexedDB API, sparse writes, deletions, ordered saves and reopening.');
