import assert from 'node:assert/strict';
import * as W from '../dist/world.mjs';
import * as T from '../dist/vendor/three.module.min.js';
import {fixture} from '../test-support/three-fixture.mjs';
import {blockObject} from '../dist/construction.mjs';
import {transparentShell,isCrystal} from '../dist/transparent-shell.mjs';
const block=(x,y,z,h=1,extra={})=>({x,y,z,h,...extra});
const area=meshes=>meshes.reduce((sum,m)=>{for(let i=0;i<m.positions.length;i+=9){const p=m.positions.slice(i,i+9),u=[p[3]-p[0],p[4]-p[1],p[5]-p[2]],v=[p[6]-p[0],p[7]-p[1],p[8]-p[2]],n=[u[1]*v[2]-u[2]*v[1],u[2]*v[0]-u[0]*v[2],u[0]*v[1]-u[1]*v[0]];if(n.reduce((s,a,j)=>s+a*m.normals[i+j],0)<=0)throw Error("Wrong winding");sum+=Math.hypot(...n)/2}return sum},0);
const wall=[];for(let x=0;x<3;x++)for(let z=0;z<2;z++)wall.push(block(x,0,z));
assert.equal(area(transparentShell(wall)),22);
assert.equal(transparentShell(wall).reduce((n,b)=>n+b.faceBlocks.length,0),44);
assert.equal(area(transparentShell([block(15,0,0),block(16,0,0)])),10);
assert.equal(area(transparentShell([block(0,0,0),block(1,0,0,.5)])),9);
assert.equal(area(transparentShell([block(0,0,0),block(0,0,1)])),10);
assert.equal(area(transparentShell([block(0,0,0),block(2,0,0)])),12);
assert.equal(area(transparentShell([block(0,0,0),block(1,0,0,1,{angle:Math.PI/2})])),10);
const a=.6;assert(Math.abs(area(transparentShell([block(0,0,0,1,{angle:a}),block(Math.cos(a),Math.sin(a),0,1,{angle:a})]))-10)<1e-8);
assert.equal(area(transparentShell([block(.5,0,0,1,{w:2}),block(2,0,0)])),14);
assert(!isCrystal('water'));assert(!isCrystal('leaves'));
// Exercise the real renderer, not only the rectangle subtraction.
const {r}=fixture(),map=W.newMap('crystal','Crystal',32,32);W.prepareBlocks(map);
map.objects=[];map.camera.mode='fly';map.camera.fly={x:12,y:6,z:13};
map.objects.push(blockObject('glass',10,10,0,1,1,1,0,'left'),blockObject('glass',11,10,0,1,1,1,0,'right'));
W.setBlock(map,13,10,0,'ice');
const opts={map,mode:'mj',selection:null,images:new Map(),lights:W.buildLights(map),vision:new Set(),explored:new Set(),terrainEpoch:1,path:[]};
r.render(opts);
const shells=()=>r.debug().reliefGroup.children.filter(m=>m.userData.transparentShell);
const glass=shells().find(m=>m.userData.crystalKind==='glass'),ice=shells().find(m=>m.userData.crystalKind==='ice');
assert(glass&&ice);assert.equal(glass.geometry.attributes.position.count,60);
assert.equal(glass.material.map,null);assert.equal(ice.material.map,null);assert(glass.material.opacity<ice.material.opacity);
assert.equal(glass.material.side,T.FrontSide);assert.equal(glass.material.depthWrite,false);assert(!glass.castShadow);
const ray=new T.Raycaster(new T.Vector3(10.5,3,10.5),new T.Vector3(0,-1,0));
const hit=ray.intersectObject(glass)[0];assert(hit);assert.equal(glass.userData.blocks[hit.instanceId].id,'left');
map.camera.angle+=.1;r.render(opts);assert.equal(shells().find(m=>m.userData.crystalKind==='glass'),glass);
map.objects.pop();opts.terrainEpoch++;r.render(opts);const one=shells().find(m=>m.userData.crystalKind==='glass');assert.equal(one.geometry.attributes.position.count,36);
r.dispose();
console.log('PASS: clean glass/ice exterior shell, partial joins, rotations, chunk seams, material settings and triangle-to-source picking.');
