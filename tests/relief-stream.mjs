import assert from 'node:assert/strict';
import * as W from '../dist/world.mjs';
import {createReliefStream} from '../dist/relief-stream.mjs';
import {buildBlockOcclusion} from '../dist/block-occlusion.mjs';
import {fixture} from '../test-support/three-fixture.mjs';
const map=W.newMap('stream','Stream',512,512);W.prepareBlocks(map);map.objects=[];
for(let x=250;x<258;x++)for(let y=250;y<258;y++)for(let z=0;z<3;z++)W.setBlock(map,x,y,z,'stone');
W.setBlock(map,400,400,0,'stone');
const regions=(...ids)=>{const chunks=new Set(ids);return {chunks,cell:(x,y)=>chunks.has(Math.floor(x/16)+','+Math.floor(y/16)),object:()=>true}};
const a=regions('15,15','16,15','15,16','16,16','14,15'),b=regions('15,15','16,15','15,16','16,16','17,15');
const stream=createReliefStream(),window=[200,200,300,300],liquids={cells:[],irregular:[]};
const s1=stream(map,a,1,window,W,liquids),s2=stream(map,b,1,window,W,liquids);
assert.equal(s1.occlusionKey,s2.occlusionKey,'empty sectors cannot invalidate occlusion');
assert.equal(s1.reliefKey,s2.reliefKey,'empty sectors cannot invalidate geometry');
assert.equal(s1.columns.length,64);
assert.deepEqual(buildBlockOcclusion(map,{columns:s1.columns,objects:s1.objects}),buildBlockOcclusion(map,{region:a}));
const {r}=fixture();Object.assign(map.camera,{mode:'fly',fly:{x:256,y:8,z:256},angle:0});
const opts={map,mode:'mj',selection:null,images:new Map(),lights:W.buildLights(map),vision:new Set(),explored:new Set(),terrainEpoch:1,path:[]};
r.render(opts);const initial=r.stats(),mesh=r.debug().reliefGroup.children.find(m=>m.userData.reliefBatch);
map.camera.angle=Math.PI;r.render(opts);assert.equal(r.stats().occlusionBuilds,initial.occlusionBuilds);assert.equal(r.stats().reliefBuilds,initial.reliefBuilds);
map.camera.fly.x=440;map.camera.fly.z=440;r.render(opts);assert(!mesh.parent,'offscreen mesh parked outside scene');
assert(r.stats().parkedReliefBatches>0);
map.camera.fly.x=256;map.camera.fly.z=256;r.render(opts);assert(mesh.parent===r.debug().reliefGroup,'return reuses the same mesh');
W.setBlock(map,250,250,0,null);opts.terrainEpoch++;r.render(opts);assert(r.stats().reliefBuilds>initial.reliefBuilds);
r.dispose();
console.log('PASS: sparse sector streaming, exact occlusion, empty-sector rotations and parked GPU mesh reuse.');
