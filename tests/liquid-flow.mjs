import assert from 'node:assert/strict';
import * as W from '../dist/world.mjs';
import {deriveLiquids,liquidMeshData,createLiquidCache} from '../dist/liquid-flow.mjs';
import {blockObject} from '../dist/construction.mjs';
const make=()=>{const m=W.newMap('liquids','Liquids',32,32);W.prepareBlocks(m);return m};
let m=make();W.setBlock(m,16,16,0,'water');
const saved=JSON.stringify(m);let result=deriveLiquids(m,W);
assert.equal(result.generated,112);assert.equal(JSON.stringify(m),saved);
assert(result.cells.some(b=>b.x===23&&b.y===16));assert(!result.cells.some(b=>b.x===24&&b.y===16));
assert(result.cells.find(b=>b.x===23&&b.y===16).renderH<result.cells.find(b=>b.x===17&&b.y===16).renderH);
assert(liquidMeshData(result).reduce((a,b)=>a+b.positions.length,0)<result.cells.length*108);
W.setBlock(m,17,16,0,'stone');assert(!deriveLiquids(m,W).cells.some(b=>b.x===17&&b.y===16));
m=make();W.setBlock(m,16,16,3,'water');result=deriveLiquids(m,W);
assert([0,1,2].every(z=>result.cells.some(b=>b.x===16&&b.y===16&&b.z===z)));assert(!result.cells.some(b=>b.z===3&&!b.source));
m=make();W.setBlock(m,16,16,0,'water');W.digGround(m,17,16);assert(deriveLiquids(m,W).cells.some(b=>b.x===17&&b.y===16&&b.z===-1));
m=make();W.setBlock(m,16,16,0,'lava');assert.equal(deriveLiquids(m,W).generated,24);
W.setBlock(m,16,16,0,'magma');assert.equal(deriveLiquids(m,W).cells.length,0);
m=make();m.objects.push(blockObject('water',16,16,0,1,1,1,0,'source'));assert.equal(deriveLiquids(m,W).generated,112);
m.objects.push(blockObject('stone',17,16,0,1,1,1,0,'wall'));assert(!deriveLiquids(m,W).cells.some(b=>b.x===17&&b.y===16));
const cache=createLiquidCache();result=cache(m,W,'mj');assert.equal(cache(m,W,'mj'),result);m.objects=[];m.buildRevision=1;assert.equal(cache(m,W,'mj').cells.length,0);
m=make();W.setBlock(m,16,16,0,'water');assert.equal(deriveLiquids(m,W,'mj',10).generated,10);
m=make();m.objects.push({...blockObject('water',16,16,0,1,1,1,0,'secret'),secret:true});assert.equal(deriveLiquids(m,W,'player').cells.length,0);
console.log('PASS: liquid sources, gravity, basin, range, obstacle, source deletion, cache, budget and exterior faces.');
