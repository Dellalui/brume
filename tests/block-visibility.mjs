import assert from 'node:assert/strict';
import fs from 'node:fs';
import {blockCutAlpha,blockCutShader} from '../dist/block-visibility.mjs';
const v=(x,y,z)=>({x,y,z});
const o=v(0,1,0),d=v(0,0,1);
assert.equal(blockCutAlpha(v(0,1,-2),o,d,5,1.8,.12),1,'never cut behind the actor');
assert.equal(blockCutAlpha(v(0,1,6),o,d,5,1.8,.12),1,'never cut behind the camera');
assert.equal(blockCutAlpha(v(0,0,2),o,d,5,1.8,.12),1,'ground stays intact');
assert.equal(blockCutAlpha(v(0,1,2),o,d,5,1.8,.12),.12);
assert.equal(blockCutAlpha(v(2,1,2),o,d,5,1.8,.12),1);
assert(blockCutAlpha(v(1.4,1,2),o,d,5,1.8,.12)>.12);
assert(blockCutShader.includes('blockCenter')&&!blockCutShader.includes('blockWorld'));
const scene=fs.readFileSync(new URL('../dist/scene.mjs',import.meta.url),'utf8');
assert(!scene.includes('blockCutAhead'));
assert(scene.includes('tacticalOutside')&&scene.includes('tacticalInside'));
assert(scene.includes('float manualFog=max(tacticalSample.g,'));
assert(!scene.includes('gl_FragColor.rgb=vec3(0.035,0.055,0.047)'));
assert(scene.includes('gpu.shadowMap.type=T.PCFShadowMap'));
assert(!fs.readFileSync(new URL('../dist/index.html',import.meta.url),'utf8').includes('id="cutaway" type="checkbox" checked'));
console.log('PASS: bounded whole-block cutaway, face-aware fog, optional cutaway and stable shadow configuration.');
